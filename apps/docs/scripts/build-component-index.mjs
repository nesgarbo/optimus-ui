/**
 * Builds the data behind /components: every component page in the navigation, with the
 * one-line description its own page already shows and the demo used as its preview.
 *
 * Run with `node scripts/build-component-index.mjs` after adding a component. The output
 * is committed so the index page needs no build step of its own.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.resolve(here, '..', 'src');

const menu = JSON.parse(fs.readFileSync(path.join(src, 'assets/data/menu.json'), 'utf8')).data;
const components = menu.find((section) => section.section === 'components');

/** `description="..."` as written on the page's own <app-doc>. */
function describe(slug) {
    const file = path.join(src, 'demos', slug, 'index.ts');

    if (!fs.existsSync(file)) {
        return '';
    }

    const source = fs.readFileSync(file, 'utf8');
    const match = source.match(/description="([^"]+)"/);

    return match ? match[1].replace(/\s+/g, ' ').trim() : '';
}

const docFolders = fs.readdirSync(path.join(src, 'doc'), { withFileTypes: true }).filter((entry) => entry.isDirectory());

/**
 * The class a `basic-doc.ts` exports — most are `BasicDoc`, a few are not — under the
 * folder's real name. One folder is `Image` while its route is `/image`, and an import
 * that only differs in casing is an error to TypeScript even where the disk allows it.
 */
function previewOf(slug) {
    const folder = docFolders.find((entry) => entry.name.toLowerCase() === slug.toLowerCase())?.name;

    if (!folder) {
        return null;
    }

    const file = path.join(src, 'doc', folder, 'basic-doc.ts');

    if (!fs.existsSync(file)) {
        return null;
    }

    const match = fs.readFileSync(file, 'utf8').match(/export class (\w+)/);

    return match ? { slug, folder, symbol: match[1] } : null;
}

const groups = components.children.map((group) => ({
    name: group.name,
    items: group.children.map((item) => {
        const slug = (item.routerLink ?? '').replace(/^\//, '');

        return {
            name: item.name,
            routerLink: item.routerLink,
            description: describe(slug),
            // The "basic" demo doubles as the card preview where a page has one.
            preview: previewOf(slug)
        };
    })
}));

const total = groups.reduce((count, group) => count + group.items.length, 0);

fs.writeFileSync(path.join(src, 'assets/data/components.json'), JSON.stringify({ total, groups }, null, 4) + '\n');

// The previews are loaded on demand, one chunk per card, so the index does not pull the
// whole library up front. A static map keeps the imports analysable.
const entries = groups
    .flatMap((group) => group.items)
    .filter((item) => item.preview)
    .map((item) => `    '${item.preview.slug}': () => import('@/doc/${item.preview.folder}/basic-doc').then((m) => m.${item.preview.symbol})`);

fs.writeFileSync(
    path.join(src, 'demos', 'components', 'previews.ts'),
    `import { Type } from '@angular/core';

/**
 * Preview for each card on /components: the component's own "basic" demo, imported on
 * demand so a card costs nothing until it scrolls into view.
 *
 * Generated by scripts/build-component-index.mjs — do not edit by hand.
 */
export const COMPONENT_PREVIEWS: Record<string, () => Promise<Type<unknown>>> = {
${entries.join(',\n')}
};
`
);

console.log(`✓ ${total} components, ${entries.length} previews`);
