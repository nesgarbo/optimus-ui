let rngState = 2024;

function seededRandom() {
    let t = (rngState += 0x6d2b79f5);

    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);

    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
}

function buildCandles(): Candle[] {
    const out: Candle[] = [];
    const firstEntry = WEEKLY[0];

    if (!firstEntry) return out;

    let prevClose = firstEntry[1];

    for (const [iso, close] of WEEKLY) {
        const ts = Date.parse(iso);
        const open = prevClose;
        const range = Math.abs(close - open) * 1.3 + 4 + seededRandom() * 6;
        const mid = (open + close) / 2;
        const high = +Math.max(open, close, mid + range / 2).toFixed(2);
        const low = +Math.min(open, close, mid - range / 2).toFixed(2);

        out.push({ ts, open: +open.toFixed(2), high, low, close });
        prevClose = close;
    }

    return out;
}

export const teslaEarnings: Candle[] = buildCandles();
